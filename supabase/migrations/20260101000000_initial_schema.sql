    END IF;

    WITH user_evals AS (
        SELECT job_id, relevance, fit_tier, matched_skills
        FROM public.user_job_evaluations
        WHERE lower(user_email) = v_caller_email
    ),
    user_stats AS (
        SELECT job_id, status
        FROM public.user_job_statuses
        WHERE lower(user_email) = v_caller_email
    ),
    combined AS (
        SELECT 
            j.id,
            j.title,
            j.company,
            j.location,
            j.employment_type,
            j.salary_text,
            j.url,
            j.source,
            COALESCE(NULLIF(TRIM(j.role_domain), ''), 'General') AS role_domain,
            j.seniority_level,
            j.last_seen_at,
            COALESCE(e.relevance, j.relevance, 0) AS relevance,
            COALESCE(e.fit_tier, j.fit_tier, 'Unassessed') AS fit_tier,
            COALESCE(e.matched_skills, j.matched_skills, '[]'::jsonb) AS matched_skills,
            COALESCE(s.status, j.status, 'new') AS status
        FROM public.jobs j
        LEFT JOIN user_evals e ON e.job_id = j.id
        LEFT JOIN user_stats s ON s.job_id = j.id
    ),
    filtered AS (
        SELECT *
        FROM combined c
        WHERE 
            (p_status IS NULL OR p_status = 'all' OR c.status = p_status)
            AND (p_domain IS NULL OR p_domain = 'all' OR c.role_domain = p_domain)
            AND (p_min_match IS NULL OR p_min_match <= 0 OR c.relevance >= p_min_match)
            AND (
                p_search IS NULL OR trim(p_search) = '' OR
                (
                    c.title ILIKE '%' || trim(p_search) || '%' OR
                    c.company ILIKE '%' || trim(p_search) || '%' OR
                    c.location ILIKE '%' || trim(p_search) || '%' OR
                    c.matched_skills::text ILIKE '%' || trim(p_search) || '%'
                )
            )
            AND (
                p_location IS NULL OR p_location = 'all' OR
                c.location ILIKE '%' || trim(p_location) || '%'
            )
            AND (
                p_salary IS NULL OR p_salary = 'all' OR
                (
                    CASE
                        WHEN p_salary = 'disclosed' THEN c.salary_text IS NOT NULL AND trim(c.salary_text) <> ''
                        WHEN p_salary = '50k' THEN (c.salary_text ~* '([5-9][0-9]|[1-9][0-9]{2}),[0-9]{3}|[5-9][0-9]k')
                        WHEN p_salary = '60k' THEN (c.salary_text ~* '([6-9][0-9]|[1-9][0-9]{2}),[0-9]{3}|[6-9][0-9]k')
                        WHEN p_salary = '70k' THEN (c.salary_text ~* '([7-9][0-9]|[1-9][0-9]{2}),[0-9]{3}|[7-9][0-9]k')
                        WHEN p_salary = '80k' THEN (c.salary_text ~* '([8-9][0-9]|[1-9][0-9]{2}),[0-9]{3}|[8-9][0-9]k')
                        ELSE TRUE
                    END
                )
            )
    )
    SELECT 
        (SELECT count(*) FROM filtered),
        COALESCE(
            (
                SELECT jsonb_agg(row_to_json(r))
                FROM (
                    SELECT * FROM filtered
                    ORDER BY 
                        CASE WHEN p_sort_by = 'match' AND p_sort_dir = 'asc' THEN relevance END ASC,
                        CASE WHEN p_sort_by = 'match' AND p_sort_dir <> 'asc' THEN relevance END DESC,
                        CASE WHEN p_sort_by = 'location' AND p_sort_dir = 'desc' THEN location END DESC,
                        CASE WHEN p_sort_by = 'location' AND p_sort_dir <> 'desc' THEN location END ASC,
                        CASE WHEN p_sort_by = 'category' AND p_sort_dir = 'desc' THEN role_domain END DESC,
                        CASE WHEN p_sort_by = 'category' AND p_sort_dir <> 'desc' THEN role_domain END ASC,
                        CASE WHEN p_sort_by = 'salary' AND p_sort_dir = 'asc' THEN salary_text END ASC,
                        CASE WHEN p_sort_by = 'salary' AND p_sort_dir <> 'asc' THEN salary_text END DESC,
                        id DESC
                    LIMIT GREATEST(p_limit, 1)
                    OFFSET GREATEST(p_offset, 0)
                ) r
            ),
            '[]'::jsonb
        )
    INTO v_total, v_items;

    RETURN jsonb_build_object(
        'total', v_total,
        'items', v_items
    );
END;
$$;

