-- Document limits trigger (max 10 CVs, max 10 Cover Letters per tenant)
CREATE OR REPLACE FUNCTION public.check_user_cv_limit()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  IF (SELECT COUNT(*) FROM public.user_cvs WHERE lower(user_email) = lower(NEW.user_email)) >= 10 THEN
    RAISE EXCEPTION 'Maximum document limit of 10 CVs reached. Please delete an existing CV before uploading a new one.';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_check_user_cv_limit ON public.user_cvs;
CREATE TRIGGER trg_check_user_cv_limit
  BEFORE INSERT ON public.user_cvs
  FOR EACH ROW
  EXECUTE FUNCTION public.check_user_cv_limit();

